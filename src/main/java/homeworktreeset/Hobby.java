package homeworktreeset;

public class Hobby {
    String name;
    int frequency;
    String country;

    public Hobby(String name, int frequency, String country) {
        this.name = name;
        this.frequency = frequency;
        this.country = country;
    }

    public String getName() {
        return name;
    }

    public String getCountry() {
        return country;

    }

}
